/** 按概率抽一句台词；未命中或没有台词时返回 null。 */
export function pickDialogueLine(
  characterId: string,
  trigger: DialogueTrigger,
): string | null {
  const lines = LINES[characterId]?.[trigger];
  if (!lines || lines.length === 0) return null;
  if (Math.random() >= DIALOGUE_CHANCES[trigger]) return null;
  return lines[Math.floor(Math.random() * lines.length)];
}
